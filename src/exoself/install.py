"""`exoself install`: put an agent into a directory, once.

Mirrors `rust/crates/exoself-cli/src/install.rs`. Three kinds of host exist and
this covers all of them:

  1. hosts that read a persona file   -> SOUL.md
  2. hosts that read a project brief  -> a managed block in AGENTS.md
  3. hosts that speak MCP             -> an entry in an mcpServers config

The certificate is written with mode "x", so running install twice never draws
a second seed, and the brief holds exactly one managed block however the file
was left.
"""

from __future__ import annotations

import json
import os
import shutil
import sys

from . import core, render

BEGIN = "<!-- exoself:begin | generated by `exoself install`, do not edit -->"
END = "<!-- exoself:end -->"
# Matched by prefix so an older or hand-edited header is still recognised.
BEGIN_PREFIX = "<!-- exoself:begin"


def hint_after_birth() -> str:
    return ("Draw one first: exoself born -o birth.json\n"
            "Then check it: exoself show birth.json --format soul")


def strip_blocks(text: str) -> str:
    """Remove every managed region, wherever it starts and however it was left.

    A region with no end marker swallows the rest of the file, because a
    half-written block means the tail is generated text too.
    """
    out = []
    rest = text
    while True:
        i = rest.find(BEGIN_PREFIX)
        if i < 0:
            out.append(rest)
            return "".join(out)
        out.append(rest[:i])
        j = rest.find(END, i)
        rest = "" if j < 0 else rest[j + len(END):]


def upsert_block(existing: str, body: str) -> str:
    """Replace the managed block, or append one. Idempotent, never two."""
    block = f"{BEGIN}\n{body.strip()}\n{END}\n"
    first = existing.find(BEGIN_PREFIX)
    if first < 0:
        out = existing.rstrip()
        return (out + "\n\n" if out else "") + block
    tail = strip_blocks(existing[first:]).lstrip("\n")
    return existing[:first] + block + tail


def merge_mcp_config(existing: str | None, entry: dict) -> dict:
    """Add or replace the exoself entry, leaving every other server and key."""
    if existing and existing.strip():
        root = json.loads(existing)
        if not isinstance(root, dict):
            raise ValueError("the MCP config is not a JSON object")
    else:
        root = {"mcpServers": {}}
    servers = root.get("mcpServers")
    if not isinstance(servers, dict):
        servers = {}
        root["mcpServers"] = servers
    servers.pop("exoself", None)
    servers["exoself"] = entry
    return root


def brief_body(ph: dict, reg: dict, state: dict, cert_path: str, state_path: str,
               desire: bool) -> str:
    """The text inside the managed block. Shared by `install` and by the refresh
    that `develop` does after a session, so the brief cannot say two things."""
    return (
        render.render_prompt(ph, reg, desire=desire).rstrip()
        + f"\n\nAgent: {ph['handle']} ({ph['id']}). "
        f"Sessions recorded: {state['events']}. Certificate: {cert_path}. "
        f"State: {state_path}.\n"
        "Record each session with `exoself develop` or the "
        "exoself_record_session MCP tool."
    )


def had_desire(text: str) -> bool:
    """Whether a generated file was rendered with appetites on. The text is
    ours, so the marker in it is a reliable answer, and it means `develop` never
    has to be told the operator's choice a second time."""
    return "These are appetites, not goals" in text


def refresh_generated(cert_path: str, state_path: str, ph: dict, reg: dict,
                      state: dict) -> list[str]:
    """Bring the generated files in an installed directory up to date after a
    session. Only files carrying our own marker are touched."""
    cert_abs = os.path.abspath(cert_path)
    state_abs = os.path.abspath(state_path)
    state_dir = os.path.dirname(cert_abs)
    if os.path.basename(state_dir) != ".exoself":
        return []          # not an installed layout; not ours to touch
    directory = os.path.dirname(state_dir)
    changed = []
    try:
        names = sorted(os.listdir(directory))
    except OSError:
        return []
    for name in names:
        if not name.endswith(".md"):
            continue
        path = os.path.join(directory, name)
        try:
            with open(path, encoding="utf-8") as f:
                existing = f.read()
        except (OSError, UnicodeDecodeError):
            continue
        if BEGIN_PREFIX in existing:
            updated = upsert_block(
                existing,
                brief_body(ph, reg, state, cert_abs, state_abs, had_desire(existing)))
        elif "generated, do not edit by hand" in existing:
            updated = render.render_soul(ph, reg, desire=had_desire(existing))
        else:
            continue
        if updated != existing:
            with open(path, "w", encoding="utf-8") as f:
                f.write(updated)
            changed.append(name)
    return changed


def mcp_command() -> list[str]:
    """How a host should start this implementation's server."""
    exe = shutil.which("exoself")
    if exe:
        return [exe]
    return [sys.executable, "-m", "exoself.cli"]


def mcp_entry(cert: str, state: str, desire: bool) -> dict:
    args = mcp_command() + ["mcp", "--cert", cert, "--state", state]
    if desire:
        args.append("--desire")
    return {"command": args[0], "args": args[1:]}


def cmd_install(a) -> int:
    from .cli import Fail, _read, _write_atomic, _write_new

    directory = os.path.abspath(a.dir)
    os.makedirs(directory, exist_ok=True)
    state_dir = os.path.join(directory, ".exoself")
    os.makedirs(state_dir, exist_ok=True)
    cert_path = os.path.join(state_dir, "birth.json")
    state_path = os.path.join(state_dir, "state.json")

    if os.path.exists(cert_path):
        cert = _read(cert_path)
    else:
        reg, reg_hash = core.load_registry(a.registry)
        cert = core.born(reg_hash, f"{reg['registry']}@{reg['version']}")
        _write_new(cert_path, cert)

    try:
        reg, reg_hash = core.load_registry(a.registry, name=cert.get("registry", ""))
    except ValueError as e:
        raise Fail(str(e))
    problems = core.verify_certificate(cert, reg_hash)
    if problems:
        raise Fail(f"certificate {cert_path} rejected: {'; '.join(problems)}\n"
                   + hint_after_birth())

    seed = bytes.fromhex(cert["seed"])
    if not os.path.exists(state_path):
        _write_atomic(state_path, core.new_state(seed, reg))
    state = _read(state_path)
    if state.get("id") != cert["id"]:
        raise Fail(f"{state_path} belongs to a different agent than {cert_path}")

    pheno = core.phenotype(seed, reg, state)
    desire = bool(a.desire)

    soul_path = os.path.join(directory, a.soul)
    soul = render.render_soul(pheno, reg, desire=desire)
    if not os.path.exists(soul_path) or open(soul_path, encoding="utf-8").read() != soul:
        with open(soul_path, "w", encoding="utf-8") as f:
            f.write(soul)

    agent_file = os.path.join(directory, a.file)
    existing = ""
    if os.path.exists(agent_file):
        with open(agent_file, encoding="utf-8") as f:
            existing = f.read()
    body = brief_body(pheno, reg, state, cert_path, state_path, desire)
    updated = upsert_block(existing, body)
    if updated != existing:
        with open(agent_file, "w", encoding="utf-8") as f:
            f.write(updated)

    mcp_note = "not written (pass --json-config <file> to add one)"
    if a.json_config:
        target = a.json_config
        if not os.path.isabs(target):
            target = os.path.join(directory, target)
        existing_cfg = None
        if os.path.exists(target):
            with open(target, encoding="utf-8") as f:
                existing_cfg = f.read()
        merged = merge_mcp_config(
            existing_cfg, mcp_entry(cert_path, state_path, desire))
        os.makedirs(os.path.dirname(target) or ".", exist_ok=True)
        _write_atomic(target, merged)
        mcp_note = f"mcpServers.exoself written to {target}"

    print(f"{pheno['handle']} ({cert['id']})")
    print(f"  certificate  {cert_path}")
    print(f"  state        {state_path}")
    print(f"  persona      {soul_path}")
    print(f"  brief block  {agent_file}")
    print(f"  mcp          {mcp_note}")
    return 0
