//! `exoself install`: put an agent into a directory, once, and leave everything
//! a harness needs.
//!
//! Three kinds of host exist in the world and this covers all of them:
//!
//!   1. Hosts that read a persona file      -> SOUL.md
//!   2. Hosts that read a project brief     -> a managed block in AGENTS.md
//!   3. Hosts that speak MCP                -> an entry in an mcpServers config
//!
//! The block is delimited so re-running install refreshes it instead of piling
//! up copies. The certificate is written with `create_new`, so running install
//! twice never draws a second seed.

use crate::json::{self, Json};
use crate::{write_atomic, write_new};
use exoself_core::develop;
use exoself_core::registry::DEFAULT_REGISTRY;
use exoself_core::{birth, phenotype, render, Certificate, Registry, State};
use std::path::{Path, PathBuf};

pub const BEGIN: &str = "<!-- exoself:begin | generated by `exoself install`, do not edit -->";
pub const END: &str = "<!-- exoself:end -->";

pub fn hint_after_birth() -> String {
    "Draw one first: exoself born -o birth.json\n\
     Then check it: exoself show birth.json --format soul"
        .to_string()
}

fn ensure_dir(p: &Path) -> Result<(), String> {
    std::fs::create_dir_all(p).map_err(|e| format!("{}: {}", p.display(), e))
}

/// Replace the managed block, or append one. Idempotent.
pub fn upsert_block(existing: &str, body: &str) -> String {
    let block = format!("{}\n{}\n{}\n", BEGIN, body.trim_end(), END);
    match (existing.find(BEGIN), existing.find(END)) {
        (Some(a), Some(b)) if b > a => {
            let mut out = String::new();
            out.push_str(&existing[..a]);
            out.push_str(&block);
            out.push_str(existing[b + END.len()..].trim_start_matches('\n'));
            out
        }
        // A block whose end marker was deleted: replace everything from the
        // start marker instead of appending a second block below it.
        (Some(a), _) => {
            let mut out = existing[..a].to_string();
            out.push_str(&block);
            out
        }
        _ => {
            let mut out = existing.trim_end().to_string();
            if !out.is_empty() {
                out.push_str("\n\n");
            }
            out.push_str(&block);
            out
        }
    }
}

fn mcp_entry(exe: &Path, cert: &Path, state: &Path) -> Json {
    Json::obj(vec![
        ("command", Json::str(exe.display().to_string())),
        (
            "args",
            Json::Array(vec![
                Json::str("mcp"),
                Json::str("--cert"),
                Json::str(cert.display().to_string()),
                Json::str("--state"),
                Json::str(state.display().to_string()),
            ]),
        ),
    ])
}

fn merge_mcp_config(existing: Option<&str>, entry: Json) -> Result<Json, String> {
    let mut root = match existing {
        Some(text) if !text.trim().is_empty() => json::parse(text)?,
        _ => Json::obj(vec![("mcpServers", Json::Object(vec![]))]),
    };
    if !matches!(root, Json::Object(_)) {
        return Err("the MCP config is not a JSON object".into());
    }
    if !matches!(root.get("mcpServers"), Some(Json::Object(_))) {
        if let Json::Object(pairs) = &mut root {
            pairs.retain(|(k, _)| k != "mcpServers");
            pairs.push(("mcpServers".to_string(), Json::Object(vec![])));
        }
    }
    if let Json::Object(pairs) = &mut root {
        if let Some((_, Json::Object(servers))) = pairs.iter_mut().find(|(k, _)| k == "mcpServers")
        {
            servers.retain(|(k, _)| k != "exoself");
            servers.push(("exoself".to_string(), entry));
        }
    }
    Ok(root)
}

pub fn cmd_install(args: &[String]) -> Result<i32, String> {
    let f = crate::Flags::parse(args, &["dir", "file", "soul", "json-config", "registry"])?;
    let dir = PathBuf::from(f.value("dir").unwrap_or("."));
    ensure_dir(&dir)?;
    // Absolute paths: an MCP host may launch the server from any working
    // directory, and a relative certificate path would then point nowhere.
    let dir = dir
        .canonicalize()
        .map_err(|e| format!("{}: {}", dir.display(), e))?;
    let state_dir = dir.join(".exoself");
    ensure_dir(&state_dir)?;

    let cert_path = state_dir.join("birth.json");
    let state_path = state_dir.join("state.json");

    let cert: Certificate = if cert_path.exists() {
        Certificate::from_json(&crate::read_json(&cert_path.display().to_string())?)
            .map_err(|e| format!("{}: {}", cert_path.display(), e))?
    } else {
        let reg = match f.value("registry") {
            Some(p) => Registry::from_path(p).map_err(|e| e.to_string())?,
            None => Registry::bundled(DEFAULT_REGISTRY).map_err(|e| e.to_string())?,
        };
        let seed = birth::os_entropy()?;
        let cert = birth::born(
            &seed,
            &reg,
            &crate::iso_now(),
            birth::attestation_self_asserted(),
        );
        write_new(&cert_path.display().to_string(), &cert.to_json())?;
        cert
    };

    let reg = Registry::resolve(&cert.registry, f.value("registry")).map_err(|e| e.to_string())?;
    let problems = birth::verify_certificate(&cert, &reg.sha256);
    if !problems.is_empty() {
        return Err(format!(
            "certificate {} rejected: {}\n{}",
            cert_path.display(),
            problems.join("; "),
            hint_after_birth()
        ));
    }

    if !state_path.exists() {
        let st = develop::new_state(&cert.seed, &reg);
        write_atomic(&state_path.display().to_string(), &st.to_json())?;
    }
    let state: State = State::from_json(&crate::read_json(&state_path.display().to_string())?)
        .map_err(|e| format!("{}: {}", state_path.display(), e))?;
    if state.id != cert.id {
        return Err(format!(
            "{} belongs to a different agent than {}",
            state_path.display(),
            cert_path.display()
        ));
    }

    let ph = phenotype::phenotype(&cert.seed, &reg, Some(&state));
    let desire = f.has("desire");

    // 1. The persona file.
    let soul_path = dir.join(f.value("soul").unwrap_or("SOUL.md"));
    let soul = render::render_soul(&ph, &reg, desire);
    if std::fs::read_to_string(&soul_path).ok().as_deref() != Some(soul.as_str()) {
        std::fs::write(&soul_path, &soul).map_err(|e| format!("{}: {}", soul_path.display(), e))?;
    }

    // 2. The block in the project brief.
    let agent_file = dir.join(f.value("file").unwrap_or("AGENTS.md"));
    let existing = std::fs::read_to_string(&agent_file).unwrap_or_default();
    let body = format!(
        "{}\n\nAgent: {} ({}). Sessions recorded: {}. Certificate: {}. State: {}.\n\
         Record each session with `exoself develop` or the exoself_record_session MCP tool.",
        render::render_prompt(&ph, &reg, desire).trim_end(),
        ph.handle,
        ph.id,
        state.events,
        cert_path.display(),
        state_path.display()
    );
    let updated = upsert_block(&existing, &body);
    if updated != existing {
        std::fs::write(&agent_file, updated)
            .map_err(|e| format!("{}: {}", agent_file.display(), e))?;
    }

    // 3. The MCP entry, if the operator asked for one.
    let mut mcp_note = String::from("not written (pass --json-config <file> to add one)");
    if let Some(target) = f.value("json-config") {
        let target_path = if Path::new(target).is_absolute() {
            PathBuf::from(target)
        } else {
            dir.join(target)
        };
        let existing = std::fs::read_to_string(&target_path).ok();
        let exe = std::env::current_exe().map_err(|e| e.to_string())?;
        let merged = merge_mcp_config(
            existing.as_deref(),
            mcp_entry(&exe, &cert_path, &state_path),
        )?;
        if let Some(parent) = target_path.parent() {
            ensure_dir(parent)?;
        }
        write_atomic(&target_path.display().to_string(), &merged)?;
        mcp_note = format!("mcpServers.exoself written to {}", target_path.display());
    }

    println!("{} ({})", ph.handle, cert.id);
    println!("  certificate  {}", cert_path.display());
    println!("  state        {}", state_path.display());
    println!("  persona      {}", soul_path.display());
    println!("  brief block  {}", agent_file.display());
    println!("  mcp          {}", mcp_note);
    Ok(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn block_is_replaced_not_appended() {
        let existing = format!(
            "# My project\n\nSome text.\n\n{}\nold body\n{}\n\ntrailing\n",
            BEGIN, END
        );
        let once = upsert_block(&existing, "new body");
        assert!(once.contains("new body"));
        assert!(!once.contains("old body"));
        assert!(once.contains("# My project"));
        assert!(once.contains("trailing"));
        let twice = upsert_block(&once, "new body");
        assert_eq!(twice, once);
        assert_eq!(twice.matches(BEGIN).count(), 1);
    }

    #[test]
    fn a_truncated_block_is_replaced_not_duplicated() {
        let broken = format!("# t\n\n{}\nhalf a body\n", BEGIN);
        let fixed = upsert_block(&broken, "whole body");
        assert_eq!(fixed.matches(BEGIN).count(), 1);
        assert!(fixed.contains("whole body"));
        assert!(!fixed.contains("half a body"));
    }

    #[test]
    fn block_is_appended_to_empty_or_plain_files() {
        assert!(upsert_block("", "x").starts_with(BEGIN));
        let app = upsert_block("# hi\n", "x");
        assert!(app.starts_with("# hi\n"));
        assert!(app.contains(BEGIN));
    }

    #[test]
    fn mcp_config_merge_preserves_other_servers_and_keys() {
        let existing = r#"{"mcpServers":{"other":{"command":"x"}},"theme":"dark"}"#;
        let entry = Json::obj(vec![("command", Json::str("/bin/exoself"))]);
        let merged = merge_mcp_config(Some(existing), entry).unwrap();
        let servers = merged.get("mcpServers").unwrap();
        assert!(servers.get("other").is_some());
        assert!(servers.get("exoself").is_some());
        assert_eq!(merged.get("theme").unwrap().as_str(), Some("dark"));
        // Running it again must not duplicate the entry.
        let again = merge_mcp_config(
            Some(&merged.pretty()),
            Json::obj(vec![("command", Json::str("/bin/exoself"))]),
        )
        .unwrap();
        let pairs = match again.get("mcpServers").unwrap() {
            Json::Object(p) => p.clone(),
            _ => panic!(),
        };
        assert_eq!(pairs.iter().filter(|(k, _)| k == "exoself").count(), 1);
    }
}
